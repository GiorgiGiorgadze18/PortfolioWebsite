"""Build static CSS and WOFF2 assets. Dev tools: fonttools + brotli; runtime needs none."""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
import shutil

root=Path(__file__).resolve().parents[1]
output=root/'assets/fonts'
output.mkdir(exist_ok=True)
faces=[]
for index,(family,weight) in enumerate(
    [('Inter',v) for v in (300,400,500,600,700,800)] +
    [('Space Grotesk',v) for v in (400,500,600,700)],1):
    font=TTFont(root/f'showroom/assets/fonts/font-{index}.ttf')
    options=subset.Options()
    selection=subset.Subsetter(options=options)
    # Current portfolio copy is English; embedded demos retain their own fonts.
    selection.populate(unicodes=subset.parse_unicodes('0000-024F,1E00-1EFF,2000-206F,2190-21FF,25A0-25FF'))
    selection.subset(font)
    font.flavor='woff2'
    name=family.lower().replace(' ','-')+'-'+str(weight)+'.woff2'
    font.save(output/name)
    faces.append(f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: {weight}; font-display: swap; src: url('../assets/fonts/{name}') format('woff2'); }}")
for license in ['inter-OFL.txt','spacegrotesk-OFL.txt']:
    shutil.copyfile(root/'showroom/assets/fonts'/license,output/license)
(root/'css/fonts.css').write_text('/* Existing portfolio font faces, locally hosted English subset. */\n'+'\n'.join(faces)+'\n')
parts=['fonts.css','tokens.css','index.css','constellation.css','experience-scroll.css','hero-motion.css','hologram.css']
bundle='/* Generated by tools/build_styles.py. Edit the source stylesheets. */\n'
for part in parts:
    bundle+='\n/* Source: '+part+' */\n'+(root/'css'/part).read_text()
(root/'css/home-bundle.css').write_text(bundle)
